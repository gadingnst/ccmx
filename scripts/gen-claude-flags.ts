#!/usr/bin/env bun
/**
 * Regenerate src/core/claude-flags.ts from the installed claude: `claude --help` for the
 * root options, plus the option definitions inside the binary for the hidden ones.
 * Run after a Claude Code update: bun scripts/gen-claude-flags.ts
 */
import { realpathSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type Arity = 'one' | 'many' | 'optional' | 'none';

const SIG = /^(?:-[a-zA-Z], )?(--[a-zA-Z-]+)(?:, (--[a-zA-Z-]+))?(?: (<[^>]+>|\[[^\]]+\]))?$/;

function parse(sig: string): { names: string[]; arity: Arity } | undefined {
  const m = sig.trim().match(SIG);
  if (!m) return undefined;
  const v = m[3];
  const arity: Arity = !v
    ? 'none'
    : v.startsWith('<')
      ? v.includes('...')
        ? 'many'
        : 'one'
      : 'optional';
  return { names: [m[1]!, m[2]].filter(Boolean) as string[], arity };
}

const help = Bun.spawnSync(['claude', '--help']).stdout.toString();
const version = Bun.spawnSync(['claude', '--version']).stdout.toString().trim();
const root = new Map<string, Arity>();
for (const line of help.split('\n')) {
  if (!/^ {2}-/.test(line)) continue;
  // Signature, then two or more spaces, then the description.
  const p = parse(line.trim().replace(/ {2,}.*/, ''));
  if (p) for (const n of p.names) root.set(n, p.arity);
}

const which = Bun.spawnSync(['which', 'claude']).stdout.toString().trim();
const strings = Bun.spawnSync(['strings', '-n', '6', realpathSync(which)]).stdout.toString();
const hidden = new Map<string, Set<Arity>>();
for (const m of strings.matchAll(
  /(?:new [A-Za-z_$]{1,3}\(|(?:option|requiredOption)\()"((?:-[a-zA-Z], )?--[a-zA-Z-]+(?: <[^>"]+>| \[[^\]"]+\])?)"/g
)) {
  const p = parse(m[1]!);
  if (!p) continue;
  for (const n of p.names) {
    if (root.has(n)) continue;
    hidden.set(n, (hidden.get(n) ?? new Set()).add(p.arity));
  }
}

const table = new Map(root);
for (const [n, set] of hidden) {
  // The same name on several subcommands with different arity: keep the flag but treat
  // its value as optional, the choice that never swallows a following flag.
  table.set(n, set.size === 1 ? [...set][0]! : 'optional');
}
for (const [short, arity] of [
  ['-n', 'one'],
  ['-d', 'optional'],
  ['-w', 'optional'],
  ['-r', 'optional']
] as const)
  table.set(short, arity);

const pick = (a: Arity) =>
  [...table]
    .filter(([, v]) => v === a)
    .map(([k]) => k)
    .sort();
const list = (xs: string[]) => xs.map((x) => `  '${x}'`).join(',\n');
const out = `// Generated by scripts/gen-claude-flags.ts from ${version}. Do not edit by hand.
// How many values each claude flag takes, so a relaunch keeps flags with their values and
// drops only the prompt. Includes options hidden from \`claude --help\`.

/** \`--model opus\`: exactly one value (taken even when it starts with a dash). */
export const ONE_VALUE = new Set([
${list(pick('one'))}
]);

/** \`--add-dir a b\`: every following word up to the next flag. */
export const MANY_VALUES = new Set([
${list(pick('many'))}
]);

/** \`--debug\` or \`--debug api\`: the next word may be the value or the prompt. */
export const OPTIONAL_VALUE = new Set([
${list(pick('optional'))}
]);
`;
writeFileSync(join(import.meta.dir, '..', 'src', 'core', 'claude-flags.ts'), out);
console.log(`wrote ${table.size} flags from ${version}`);
